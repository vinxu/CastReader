#!/usr/bin/env python3
"""Fail closed if a re-export reintroduces models or bypasses persistent storage."""
import hashlib,json,sys,re
from pathlib import Path
root=Path(__file__).resolve().parents[2]
m=json.loads((root/'scripts/ocr/models.json').read_text())
keep={'eng','hin','ell','heb','fin','hun','fil'}
app=Path(sys.argv[1]) if len(sys.argv)>1 else None
paths=list(app.rglob('*.traineddata')) if app else list((root/'CastReader').rglob('*.traineddata'))+list((root/'CastReader Safari Extension').rglob('*.traineddata'))
assert len(paths)==len(keep) and {p.stem for p in paths}==keep, 'Unexpected/duplicate bundled OCR models'
for p in paths:
 a=m[p.stem];assert p.stat().st_size==a['bytes'] and hashlib.sha256(p.read_bytes()).hexdigest()==a['sha256'],p
 if app:assert 'CastReader Safari Extension.appex' in p.parts, p
resources=(app/'PlugIns/CastReader Safari Extension.appex') if app else root/'CastReader Safari Extension/Resources'
s=(resources/'chunks/audio-manager-C4VH5vTy.js').read_text()
assert 'async function et(i){const data=await loadNativeOCRModel(i,k[i]);await D(i,data);return data}' in s,'Safari model loader bypasses native shared store'
assert s.startswith('import { loadNativeOCRModel } from "./native-ocr-models.js";'), 'Native adapter missing'
background=(resources/'background.js').read_text()
assert 'async function Si(t){const data=await globalThis.castReaderNativeOCR(t,It[t]);await Gr(t,data);return data}' in background,'Safari background bypasses durable store'
manifest=json.loads((resources/'manifest.json').read_text())
assert manifest['background']['scripts'][0]=='chunks/native-ocr-models-background.js'
adapter=(resources/'chunks/native-ocr-models.js').read_text().replace('export async function','async function')
expected='// Generated by scripts/ocr/install-safari-loader.mjs.\n(function () {\n'+adapter+'\nglobalThis.castReaderNativeOCR = loadNativeOCRModel;\n})();\n'
assert (resources/'chunks/native-ocr-models-background.js').read_text()==expected,'Regenerate classic background adapter'

# Browser/native pins must match; a valid binary with a mismatched manifest is unusable.
registry=s.split(',k={',1)[1].split(',K="castreader-ocr-model-data',1)[0]
rows=re.findall(r'(?:^|,)([a-z_]+):\{url:"([^"]+)",fallbackUrls:\["([^"]+)"\],bytes:(\d+),sha256:"([0-9a-f]{64})"\}',registry)
observed={name:{'url':url,'fallbackUrls':[mirror],'bytes':int(size),'sha256':sha} for name,url,mirror,size,sha in rows}
assert observed=={k:v for k,v in m.items() if k!='jpn_vert'},'Browser/native model catalog mismatch'
if not app:
 swift=(root/'CastReader/Services/OCRModelCatalog.swift').read_text()
 for name,asset in m.items():
  expected=f'"{name}": OCRModelAsset(id: "{name}", bytes: {asset["bytes"]}, sha256: "{asset["sha256"]}", sources: ['
  expected+=', '.join('URL(string: '+json.dumps(u)+')!' for u in [asset['url'],*asset['fallbackUrls']])+']),'
  assert expected in swift, 'Regenerate the native catalog: '+name

# Main and extension WASM stay bundled; executable code is never downloaded.
for base in [app/'WebAssets/KindleOCR' if app else root/'CastReader/WebAssets/KindleOCR',resources]:
 for filename in ['tesseract-core.wasm','tesseract-core-fallback.wasm']:
  assert (base/'tesseract-wasm'/filename).stat().st_size>0
if app:
 glot=list(app.rglob('glotlid-v3-q300k.ftz'))
 assert len(glot)==1 and hashlib.sha256(glot[0].read_bytes()).hexdigest()=='3b654fe9280b7ccc18c96d7fd12393437dd7191304bb359258e34ae0b58f1fea','GlotLID must remain unchanged'
print(json.dumps({'scope':'built app' if app else 'source','bundledModels':sorted(keep),'ocrBytes':sum(p.stat().st_size for p in paths),'status':'PASS'}))
