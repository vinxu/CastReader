#!/usr/bin/env python3
"""Generate the product scope, never a pretend runtime voice/OCR catalog."""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[1]
config = json.loads((root / "config/ios-language-capabilities.json").read_text())
languages = config["languages"]
assert len(languages) == 28 and len({x["code"] for x in languages}) == 28
assert not set(config["excluded"]) & {x["code"] for x in languages}
assert config['serviceRegions']['global'] == [x['code'] for x in languages]
assert config['serviceRegions']['cn'] == [x['code'] for x in languages if x['engine'] == 'kokoro']
quote = lambda value: json.dumps(value, ensure_ascii=False)
lines = ["// Generated by scripts/generate-ios-language-capabilities.py. Do not edit.",
         "import Foundation", "", "enum SupportedTTSLanguage: String, CaseIterable, Identifiable {"]
lines += [f'    case {x["swiftCase"]} = {quote(x["code"])}' for x in languages]
lines += ['    var id: String { rawValue }', '    static let policyVersion = ' + quote(config['version']),
          '    static let excludedCodes: Set<String> = [' + ', '.join(map(quote, config['excluded'])) + ']']
lines += ['    /// Product scope is distinct from the currently available server catalog.',
          '    static func supported(in route: ServiceRoute) -> [Self] {',
          '        route == .chinaGateway ? allCases.filter { chinaCodes.contains($0.rawValue) } : allCases',
          '    }',
          '    static var currentServiceLanguages: [Self] { supported(in: ServiceRouting.current) }',
          '    func isSupported(in route: ServiceRoute) -> Bool { Self.supported(in: route).contains(self) }',
          '    private static let chinaCodes: Set<String> = [' + ', '.join(map(quote, config['serviceRegions']['cn'])) + ']']
for prop, field in [('localeIdentifier', 'locale'), ('nativeName', 'nativeName'), ('engine', 'engine'),
                    ('defaultVoiceID', 'offlineVoice'), ('defaultVoiceName', 'offlineName')]:
    lines += [f'    var {prop}: String {{', '        switch self {']
    lines += [f'        case .{x["swiftCase"]}: return {quote(x[field])}' for x in languages]
    lines += ['        }', '    }']
lines += ['''    var isGoogle: Bool { engine == "google" || engine == "google-wavenet" }
    var bundledOCRModel: String? {
        switch self {
        case .english: return "eng"
        case .chinese: return "chi_sim"
        case .japanese: return "jpn"
        case .spanish: return "spa"
        case .french: return "fra"
        case .german: return "deu"
        case .brazilianPortuguese: return "por"
        case .italian: return "ita"
        case .hindi: return "hin"
        case .finnish: return "fin"
        case .greek: return "ell"
        case .hungarian: return "hun"
        case .filipino: return "fil"
        case .hebrew: return "heb"
        default: return nil
        }
    }
    var isRightToLeft: Bool { self == .arabic || self == .hebrew }
    var catalogName: String { Locale(identifier: "en").localizedString(forLanguageCode: rawValue) ?? nativeName }
    var timestampMode: String { self == .chinese || self == .japanese ? "segment" : "word" }
    var visionRecognitionLanguage: String {
        if self == .chinese { return "zh-Hans" }
        if self == .arabic { return "ar-SA" }
        return localeIdentifier
    }
    func availableVisionLocale(in available: Set<String>) -> String? {
        if available.contains(visionRecognitionLanguage) { return visionRecognitionLanguage }
        // Vision may expose an OS-specific spelling (e.g. vi-VT on iOS 26.2).
        // Match only this exact canonical language, never a neighbouring language.
        return available.sorted().first { Self(identifier: $0) == self }
    }

    /// Content aliases only. `no` is ambiguous and `nn` is not Bokmål.
    static func normalizedIdentifier(_ identifier: String) -> String {
        let primary = identifier.trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased().replacingOccurrences(of: "_", with: "-")
            .split(separator: "-").first.map(String.init) ?? ""
        return aliases[primary] ?? primary
    }
    init?(identifier: String) { self.init(rawValue: Self.normalizedIdentifier(identifier)) }
    /// Preserve unsupported/unknown labels so no caller can silently speak English.
    static func canonicalCode(_ identifier: String) -> String { normalizedIdentifier(identifier) }
    private static let aliases: [String: String] = [''']
aliases = {alias:x['code'] for x in languages for alias in x['aliases']}
aliases.update({'tl':'fil', 'iw':'he', 'in':'id'})
assert 'no' not in aliases and 'nn' not in aliases
lines += [f'        {quote(k)}: {quote(v)},' for k,v in sorted(aliases.items())]
lines += ['    ]', '}', '']
output = '\n'.join(lines)
target = root / 'CastReader/Utils/SupportedTTSLanguage.swift'
if '--check' in sys.argv:
    assert target.read_text() == output, 'Generated language capabilities are stale'
else:
    target.write_text(output)
