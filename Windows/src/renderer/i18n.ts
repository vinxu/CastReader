export function errorMessage(code: string, locale: string) {
  return locale.startsWith("zh")
    ? (messages[code] ?? `操作未完成（${code}）`)
    : `Unable to complete this action (${code.replaceAll("_", " ").toLowerCase()}). Please try again.`;
}
